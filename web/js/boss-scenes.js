/* ============================================================================
 * boss-scenes.js — the boss roster from mods/boss-rush, usable from the page
 * ----------------------------------------------------------------------------
 * `mods/boss-rush` ships the catalogue (BossScenes/BossSceneConfig.json) and one
 * prepared save per boss (BossScenes/BossSave/<name>.json.gz). The page can use
 * the same files:
 *
 *   • the start screen lists the roster, so you can see what is installed;
 *   • "Boss saves" in the menu drops a chosen boss save into a save slot, which
 *     is what the boss-rush / RL mods do on the desktop build.
 *
 * The files are *not* duplicated in git: tools/stage-boss-scenes.mjs copies
 * them into web/BossScenes/ (git-ignored) when you want them, and everything
 * here degrades to "not installed" when they are missing.
 *
 * The saves in the repo are gzipped JSON; the game wants the .dat container, so
 * the codec (js/save-codec.js) turns one into the other in the browser.
 *
 * Saves live inside Unity's IDBFS IndexedDB database ("/idbfs" → FILE_DATA),
 * where the key is `/idbfs/<build hash>/<file name>`; the hash is generated by
 * Unity from companyName + productName, so it is discovered from the existing
 * keys rather than assumed.
 * ==========================================================================*/

(function (global) {
  'use strict';

  var CONFIG_PATH = 'BossScenes/BossSceneConfig.json';
  var SAVE_DIR = 'BossScenes/BossSave/';
  var IDBFS_DB = '/idbfs';
  var IDBFS_STORE = 'FILE_DATA';

  function abs(base, path) {
    if (!base) return path;
    return String(base).replace(/\/$/, '') + '/' + path;
  }

  /* ---------------------------------------------------------------- *
   * Catalogue
   * ---------------------------------------------------------------- */

  var cache = null;

  /** Fetch the boss catalogue. Resolves to null when it is not staged. */
  async function list(opts) {
    opts = opts || {};
    if (cache && !opts.force) return cache;
    var url = abs(opts.base, CONFIG_PATH);
    var fetchImpl = opts.fetch || fetch;
    try {
      var res = await fetchImpl(url, { cache: 'no-cache' });
      if (!res.ok) return null;
      var data = await res.json();
      var bosses = (data && data.BossScenes) || [];
      cache = bosses.map(function (b) {
        return {
          name: b.BossName,
          scene: b.SceneName,
          x: b.PosX,
          y: b.PosY,
          z: b.PosZ,
          save: SAVE_DIR + b.BossName + '.json.gz',
          installed: null,
        };
      });
      return cache;
    } catch (e) {
      return null;
    }
  }

  function saveUrl(name, base) {
    return abs(base, SAVE_DIR + name + '.json.gz');
  }

  /**
   * Read one boss save and return the bytes the game wants (.dat container).
   * Understands `.json.gz` (the repo's format) as well as plain `.dat`/JSON.
   */
  async function loadSave(name, opts) {
    opts = opts || {};
    var fetchImpl = opts.fetch || fetch;
    var codec = opts.codec || global.SKSaveCodec;
    if (!codec) throw new Error('save codec is not loaded');
    var res = await fetchImpl(abs(opts.base, SAVE_DIR + name + '.json.gz'), { cache: 'default' });
    if (!res.ok) throw new Error('HTTP ' + res.status + ' for the save of ' + name);
    var bytes = new Uint8Array(await res.arrayBuffer());
    var json = await codec.findSaveOrGzip(bytes);
    return { json: json, dat: codec.encodeDat(json) };
  }

  /* ---------------------------------------------------------------- *
   * IDBFS (Unity's IndexedDB file system)
   * ---------------------------------------------------------------- */

  function supported() {
    return typeof indexedDB !== 'undefined';
  }

  function openDb() {
    return new Promise(function (resolve, reject) {
      var req = indexedDB.open(IDBFS_DB);
      req.onsuccess = function () { resolve(req.result); };
      req.onerror = function () { reject(req.error || new Error('could not open ' + IDBFS_DB)); };
    });
  }

  /** The hash Unity uses for this build's folder, taken from existing keys. */
  function hashFromKeys(keys) {
    for (var i = 0; i < keys.length; i++) {
      var parts = String(keys[i]).split('/');
      if (parts.length > 2 && parts[1] === 'idbfs' && parts[2]) return parts[2];
    }
    return null;
  }

  /**
   * List the save slots the game has written, with their sizes.
   * Returns {hash, slots: [{slot, name, bytes}], files: [...]}.
   */
  async function slots() {
    if (!supported()) return { hash: null, slots: [], files: [] };
    var db = await openDb();
    if (!db.objectStoreNames.contains(IDBFS_STORE)) return { hash: null, slots: [], files: [] };
    return new Promise(function (resolve) {
      var tx = db.transaction(IDBFS_STORE, 'readonly');
      var store = tx.objectStore(IDBFS_STORE);
      var keysReq = store.getAllKeys();
      keysReq.onsuccess = function () {
        var keys = keysReq.result || [];
        var hash = hashFromKeys(keys);
        var files = [];
        var pending = 0;
        if (!keys.length) return resolve({ hash: null, slots: [], files: [] });
        keys.forEach(function (key) {
          var name = String(key).split('/').pop();
          if (!/^user\d+\.dat$/i.test(name)) return;
          pending++;
          var getReq = store.get(key);
          getReq.onsuccess = function () {
            var entry = getReq.result;
            var size = entry && entry.contents && entry.contents.length ? entry.contents.length : 0;
            var slot = parseInt(/user(\d+)/i.exec(name)[1], 10);
            files.push({ key: String(key), name: name, slot: slot, bytes: size });
            if (--pending === 0) done();
          };
          getReq.onerror = function () {
            if (--pending === 0) done();
          };
        });
        function done() {
          files.sort(function (a, b) { return a.slot - b.slot; });
          resolve({ hash: hash, slots: files.filter(function (f) { return f.bytes > 0; }), files: files });
        }
        if (!pending) done();
      };
      keysReq.onerror = function () { resolve({ hash: null, slots: [], files: [] }); };
    });
  }

  /** Read one slot's raw bytes. */
  async function readSlot(slot) {
    if (!supported()) return null;
    var db = await openDb();
    if (!db.objectStoreNames.contains(IDBFS_STORE)) return null;
    var info = await slots();
    var hash = info.hash;
    if (!hash) return null;
    return new Promise(function (resolve) {
      var tx = db.transaction(IDBFS_STORE, 'readonly');
      var req = tx.objectStore(IDBFS_STORE).get('/idbfs/' + hash + '/user' + slot + '.dat');
      req.onsuccess = function () {
        var entry = req.result;
        if (!entry || !entry.contents || !entry.contents.length) return resolve(null);
        var bytes = entry.contents instanceof Uint8Array ? entry.contents : new Uint8Array(entry.contents);
        resolve(bytes);
      };
      req.onerror = function () { resolve(null); };
    });
  }

  /**
   * Write bytes into `user<slot>.dat` (this is what the game reads on boot).
   * The entry has the same shape Unity's IDBFS writes: Int8Array contents.
   */
  async function writeSlot(slot, bytes) {
    if (!supported()) throw new Error('this browser has no IndexedDB');
    var db = await openDb();
    if (!db.objectStoreNames.contains(IDBFS_STORE)) {
      throw new Error('start the game once so it creates its save database');
    }
    var info = await slots();
    var hash = info.hash;
    if (!hash) throw new Error('start the game once (and save once) so the save folder exists');
    var contents = bytes instanceof Int8Array ? bytes : new Int8Array(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
    return new Promise(function (resolve, reject) {
      var tx = db.transaction(IDBFS_STORE, 'readwrite');
      var store = tx.objectStore(IDBFS_STORE);
      store.put(
        { timestamp: new Date(), mode: 33206 /* 0666 */, contents: contents },
        '/idbfs/' + hash + '/user' + slot + '.dat'
      );
      tx.oncomplete = function () { resolve({ slot: slot, bytes: contents.length, hash: hash }); };
      tx.onerror = function () { reject(tx.error || new Error('the write was rejected')); };
    });
  }

  /**
   * Install a boss save into a slot: download → gunzip → decode → .dat → IDBFS.
   * Reload the page afterwards; the game reads the slot on boot.
   */
  async function install(name, slot, opts) {
    opts = opts || {};
    if (opts.log) opts.log('boss saves: loading ' + name + '…');
    var loaded = await loadSave(name, opts);
    var written = await writeSlot(slot, loaded.dat);
    if (opts.log) opts.log('boss saves: ' + name + ' → slot ' + slot + ' (' + written.bytes + ' bytes, folder ' + written.hash + ')');
    return Object.assign({ name: name, json: loaded.json }, written);
  }

  global.SKBossScenes = {
    CONFIG_PATH: CONFIG_PATH,
    SAVE_DIR: SAVE_DIR,
    list: list,
    saveUrl: saveUrl,
    loadSave: loadSave,
    slots: slots,
    readSlot: readSlot,
    writeSlot: writeSlot,
    install: install,
    supported: supported,
  };
  if (typeof module === 'object' && module.exports) module.exports = global.SKBossScenes;
})(typeof window !== 'undefined' ? window : globalThis);
